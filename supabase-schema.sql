CREATE TABLE IF NOT EXISTS clientes (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre   TEXT NOT NULL,
  telefono TEXT NOT NULL DEFAULT '',
  doc      TEXT NOT NULL DEFAULT '',
  monto    NUMERIC(14,2) NOT NULL CHECK (monto > 0),
  tasa     NUMERIC(6,2) NOT NULL CHECK (tasa >= 0),
  fecha    DATE NOT NULL,
  creado   TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS pagos (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
  mes        INT NOT NULL CHECK (mes >= 1),
  fecha      DATE NOT NULL,
  monto      NUMERIC(14,2) NOT NULL CHECK (monto >= 0),
  UNIQUE (cliente_id, mes)
);

CREATE INDEX IF NOT EXISTS idx_pagos_cliente ON pagos(cliente_id);

CREATE TABLE IF NOT EXISTS abonos_capital (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id BIGINT NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
  fecha      DATE NOT NULL,
  monto      NUMERIC(14,2) NOT NULL CHECK (monto > 0)
);

CREATE INDEX IF NOT EXISTS idx_abonos_capital_cliente ON abonos_capital(cliente_id);

-- Habilitar Row Level Security (RLS) y permitir acceso
ALTER TABLE clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE pagos ENABLE ROW LEVEL SECURITY;
ALTER TABLE abonos_capital ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Acceso autenticado clientes" ON clientes;
CREATE POLICY "Acceso clientes" ON clientes
  FOR ALL TO anon, authenticated
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso autenticado pagos" ON pagos;
CREATE POLICY "Acceso pagos" ON pagos
  FOR ALL TO anon, authenticated
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Acceso autenticado abonos_capital" ON abonos_capital;
CREATE POLICY "Acceso abonos_capital" ON abonos_capital
  FOR ALL TO anon, authenticated
  USING (true) WITH CHECK (true);
